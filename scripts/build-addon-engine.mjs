// Bundles @blockingmachine/https-filter into a single ESM file for the
// Home Assistant add-on. The add-on image is dependency-free by design (no
// npm install in its Dockerfile), so the engine ships as one vendored
// artifact — packages/homeassistant-addon/engine.mjs — the same shape the
// repo already keeps under vendor/. Run after any https-filter/core change
// that should reach the add-on:
//
//   node scripts/build-addon-engine.mjs
//
// Requires `packages/https-filter` to be built first (npm run build -w
// packages/https-filter). node-forge resolves through the workspace's
// vendored copy automatically (file: dep → node_modules symlink).
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

const shared = {
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node18',
  minify: false,
  sourcemap: false,
  banner: {
    // node-forge/dns-packet are CJS and call require('crypto') — in ESM
    // output that dynamic require doesn't exist, so hand the bundle a real
    // one. Aliased because bundled modules can declare createRequire too.
    js: '// GENERATED by scripts/build-addon-engine.mjs — do not edit. Rebuild after https-filter/system-daemon/core changes.\n' +
      "import { createRequire as __bmCreateRequire } from 'node:module'; const require = __bmCreateRequire(import.meta.url);",
  },
};

// The HTTPS-filter engine — explicit proxy on :9294.
await build({
  ...shared,
  entryPoints: [join(root, 'packages/https-filter/dist/index.js')],
  outfile: join(root, 'packages/homeassistant-addon/engine.mjs'),
});

// The DNS daemon — the filtering resolver a router's DHCP can hand out on :53.
await build({
  ...shared,
  entryPoints: [join(root, 'packages/system-daemon/dist/index.js')],
  outfile: join(root, 'packages/homeassistant-addon/dns-daemon.mjs'),
});

console.log('✓ packages/homeassistant-addon/engine.mjs + dns-daemon.mjs');
